# -*- coding: utf-8 -*-
"""三项决策放到**同一把尺**上比。

★★★ 尺是项目一直用的那把: **净增益 = 鉴别格对数 − 多数类格错数**。
三个问题问的是三件不同的事(合同措辞 / 语料来源 / 供应商保证), 但落到这把尺上
才看得出它们是不是同一堵墙。

★★★ 本文件**不产生任何新数字** —— 每个数都从三份已有产物里现取。
    「一个数只写在一个地方 —— 现算的那个」。
★ 零调用。
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = {
    "①": ROOT / "results/interpretation_upgrade_impact.json",
    "②": ROOT / "results/real_corpus_feasibility.json",
    "③": ROOT / "results/seed_probe.json",
}
OUT = ROOT / "results/three_decisions_rollup.json"


def _k(d, frag):
    """按片段取键 —— 键名带★, 写死会和产物脱钩。"""
    ks = [x for x in d if frag in x]
    if len(ks) != 1:
        raise KeyError("★ 片段 %r 在产物里命中 %d 个键(应为 1): %r" % (frag, len(ks), ks))
    return d[ks[0]]


def main():
    miss = [k for k, p in SRC.items() if not p.exists()]
    if miss:
        print("★ 缺产物: %r —— 先跑对应探针" % miss, file=sys.stderr)
        return 1
    D = {k: json.loads(p.read_text(encoding="utf-8")) for k, p in SRC.items()}

    # ── ① 升合同: 在**真实证书**上能新增几个鉴别格 ────────────────────
    ex = _k(D["①"], "这两条规则在真实证书上被 exercise 了吗")
    rep_n = _k(ex, "citation == REPORTED 出现次数")
    nok_n = _k(ex, "predicate == NOT_OF_DECLARED_KIND 出现次数")
    d1 = {
        "问的是": "五类成立条件要不要从「解释」升成「合同明文」",
        "★真实证书上两条规则被触发的次数": {"REPORTED": rep_n, "NOT_OF_DECLARED_KIND": nok_n},
        "★真实证书上的新增鉴别格": rep_n + nok_n,
        "★为什么是这个数": "两条规则一次都没被 exercise ⇒ 升与不升在真实数据上**逐字节同结果**。"
                           "收益只在手构对照上看得见, 而手构对照与真人语料有 19–30 个百分点的表层偏离。",
        "★卡在哪": "**效度** —— 不是规则写得不对, 是**没有能检验它的格子**。",
    }

    # ── ② 换真实语料: 能拿到几个鉴别格 ────────────────────────────────
    cost = _k(D["②"], "代价估算")
    d2 = {
        "问的是": "对照集改用真实语料重建, 可行吗",
        "★现成可标的鉴别格": 0,
        "★为什么是 0": _k(D["②"], "所以可行吗")[:120] + "…",
        "★要买到 24 个鉴别格的外推代价": cost,
        "★卡在哪": "**效度** —— RESTATES_IDENTIFIER 是**抽取错误类别**不是语言现象, "
                   "人从语料里标不出来; 要拿到格子只能先花调用。",
    }

    # ── ③ 要确定性保证: 能新增几个鉴别格 ─────────────────────────────
    uniq = D["③"]["逐组不同输出数"]
    dgrp = [k for k in uniq if k.startswith("D")][0]
    d3 = {
        "问的是": "要不要向 MiniMax 要可验证的确定性保证",
        "★实测": "temp=0.0 同一 prompt %d 次 → **%d 种不同输出**; seed 发了不起作用。"
                 % (D["③"]["逐组样本数"][dgrp], uniq[dgrp]),
        "★新增鉴别格": 0,
        "★为什么是 0": "确定性是**可复现**属性(同样输入给同样输出), 鉴别格是**效度**问题"
                       "(这道题分不分得出对错)。**即便 seed 明天就生效, 一个格子也不会多出来。**",
        "★卡在哪": "它**不在**当前这堵墙上 —— 但它解释了另一件事(见下)。",
    }

    gains = [d1["★真实证书上的新增鉴别格"], d2["★现成可标的鉴别格"], d3["★新增鉴别格"]]
    out = {
        "block": "THREE_DECISIONS_ROLLUP",
        "★零调用": "只读三份已有产物, **不发起任何模型调用**, 也不产生任何新数字。",
        "★尺": "净增益 = 鉴别格对数 − 多数类格错数。三项都换算成「**在真实证书上能新增几个鉴别格**」。",
        "①": d1, "②": d2, "③": d3,
        "★★★★★ 三项同尺后的读数": {
            "逐项新增鉴别格": {"①升合同": gains[0], "②换真实语料": gains[1], "③要确定性": gains[2]},
            "合计": sum(gains),
            "★★★这才是结论": "三个问题问的是**三件不同的事**(合同措辞 / 语料来源 / 供应商保证), "
                "但换到同一把尺上, **三项的答案都是 0**。"
                "⇒ 挡住的不是这三件事里的任何一件, 是**同一堵墙: 没有鉴别格**。"
                "★ 所以「三项都做」做完之后, **该做的下一件事不在这三项里** —— "
                "是 ②(a) 那条: **花 ~50 次调用做小批试**, 把 ~570 次的外推换成实测值。"
                "那是三条路里**唯一一条能把「没有格子」变成「有几个格子」**的。",
        },
        "★★★③ 虽然不在墙上, 但它换掉了一个此前的解释": {
            "r3 当时说什么": "同一仪器重测一致率 60%, 且明写 **k=6 不能单独归因于模型随机性**(也可能是服务端变更)。",
            "本轮换掉了什么": "seed 探针的多次调用是**同一时刻并发**发出的, 仍然 %d/%d 不同 "
                              "⇒ **服务端变更这个解释被排除**, 剩下的是模型自身的非确定性。"
                              % (uniq[dgrp], D["③"]["逐组样本数"][dgrp]),
            "★这对项目的含义": "CCE 的重测一致率**有一个不可消除的下界**, 它来自模型而不是链路。"
                               "⇒ 任何「提高一致率」的工作都得先把这个下界测出来, 否则是在跟噪声较劲。",
            "★但不得外推": "单一 prompt、单一模型、n 很小。它**不是**对 CCE 全链路一致率的测量。",
        },
        "★★★这份东西不做裁定": "升不升、换不换、要不要问供应商, **都是 owner 的决定**。"
                               "本文件只把三项换算到同一把尺上, 让「它们是不是同一个问题」变得可见。",
        "★来源": {k: str(p.relative_to(ROOT)) for k, p in SRC.items()},
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("三项同尺 · 逐项新增鉴别格:", json.dumps(
        out["★★★★★ 三项同尺后的读数"]["逐项新增鉴别格"], ensure_ascii=False))
    print("合计:", out["★★★★★ 三项同尺后的读数"]["合计"])
    print("→", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
